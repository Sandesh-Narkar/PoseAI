def _get_api_key() -> str:
    """Read GEMINI_API_KEY or GOOGLE_API_KEY from process environment."""
    key = os.environ.get("GEMINI_API_KEY", "").strip()
    if not key:
        key = os.environ.get("GOOGLE_API_KEY", "").strip()
    return key


def is_gemini_available() -> bool:
    """Return True if an API key is set and google-genai is installed."""
    if not _get_api_key():
        return False
    try:
        from google import genai  # type: ignore # noqa: F401
        return True
    except ImportError:
        return False


def _create_genai_client() -> Any:
    """Initialize google-genai Client."""
    api_key = _get_api_key()
    if not api_key:
        return None
    try:
        from google import genai
        return genai.Client(api_key=api_key)
    except Exception as exc:
        logger.warning("Could not initialize google-genai client: %s", exc)
        return None


def _prepare_image_part(img: np.ndarray) -> Optional[Any]:
    """Convert OpenCV BGR image or PIL Image to a google-genai Part."""
    try:
        from google.genai import types

        if isinstance(img, np.ndarray):
            rgb = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
            pil_img = Image.fromarray(rgb)
        elif isinstance(img, Image.Image):
            pil_img = img.convert("RGB")
        else:
            return None

        # Resize large image to max 1280px on longest side for low latency
        max_dim = 1280
        w, h = pil_img.size
        if max(w, h) > max_dim:
            scale = max_dim / max(w, h)
            pil_img = pil_img.resize((int(w * scale), int(h * scale)), Image.Resampling.LANCZOS)

        buffer = io.BytesIO()
        pil_img.save(buffer, format="JPEG", quality=85)
        return types.Part.from_bytes(data=buffer.getvalue(), mime_type="image/jpeg")
    except Exception as exc:
        logger.error("Failed to prepare image Part for Gemini: %s", exc)
        return None


