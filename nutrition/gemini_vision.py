"""
PoseAI Nutrition Intelligence — Multi-Candidate Gemini Vision Recognition & Contradiction Engine
================================================================================================
Implements the 42-point Master Architecture:
- Structured Pydantic outputs: FoodCandidate & FoodRecognition
- Multi-candidate generation (up to 5 candidates)
- Evidence-based contradiction checks (e.g. penalizing Chicken Curry for bread/pav meals)
- Application-level confidence calculation (margin between 1st and 2nd candidates)
- Three explicit confidence states: "high", "medium", "needs_confirmation"
- Developer debug trace generation
- Multi-model fallback chain ("gemini-3.6-flash", "gemini-flash-latest", "gemini-3.5-flash", "gemini-2.5-flash")
"""

from __future__ import annotations

import io
import json
import logging
import os
import re
from typing import Any, List, Optional, Tuple

import cv2
import numpy as np
from PIL import Image
from pydantic import BaseModel, Field

logger = logging.getLogger("poseai.nutrition.gemini_vision")

# Candidate model list with automatic fallback
GEMINI_MODELS = [
    os.environ.get("GEMINI_MODEL", "").strip() or "gemini-3.6-flash",
    "gemini-flash-latest",
    "gemini-3.5-flash",
    "gemini-2.5-flash",
]


# ---------------------------------------------------------------------------
# 1. Pydantic Structured Output Schemas (Requirements 5 & 6)
# ---------------------------------------------------------------------------

class FoodCandidate(BaseModel):
    """A distinct food candidate generated by visual inspection."""
    name: str = Field(description="Name of the food candidate, e.g. 'Vada Pav', 'Dabeli', 'Batata Vada', 'Chicken Curry'")
    visual_reason: str = Field(description="Concise visual explanation of why this food matches the image")
    supporting_evidence: list[str] = Field(default_factory=list, description="Specific visual features directly supporting this candidate (e.g. 'pav bun', 'fried potato patty', 'dry red garlic chutney', 'sandwich structure')")
    contradicting_evidence: list[str] = Field(default_factory=list, description="Visible features that contradict or weaken this candidate (e.g. 'no visible chicken pieces', 'no gravy bowl', 'sandwich structure contradicts curry')")
    visual_score: float = Field(ge=0.0, le=1.0, description="Raw visual match score from 0.0 to 1.0 reflecting visible evidence strength")


class FoodRecognition(BaseModel):
    """Structured visual food recognition containing up to 5 evaluated candidates."""
    food_present: bool = Field(description="Whether food, beverage, or meal is clearly visible in the image")
    food_type: str = Field(default="street_food", description="Visual food category (e.g., 'sandwich_bun', 'curry_bowl', 'bread', 'rice_dish', 'snack', 'drink')")
    candidates: list[FoodCandidate] = Field(default_factory=list, description="Up to 5 ranked food candidates derived from visual evidence")
    image_quality: float = Field(default=0.9, ge=0.0, le=1.0, description="Clarity and lighting quality score from 0.0 to 1.0")
    requires_confirmation: bool = Field(default=False, description="True if visual evidence is ambiguous or candidates are closely matched")
    recognition_note: str = Field(default="", description="Diagnostic observation regarding visual clarity, regional style, or distinctive traits")


