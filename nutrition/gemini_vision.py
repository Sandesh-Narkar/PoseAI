# 4. Contradiction Engine & Re-Ranking (Requirements 8, 10, 11)
# ---------------------------------------------------------------------------

def apply_contradiction_penalties(
    candidates: list[FoodCandidate],
    image_quality: float,
) -> Tuple[list[FoodCandidate], dict[str, Any]]:
    """
    Evaluate explicit contradictions and re-rank candidates deterministically.

    Rules:
    - If a candidate is Chicken Curry / Meat Curry, but supporting evidence mentions
      'pav', 'bun', 'bread', 'sandwich', 'dry filling', or contradicting evidence mentions
      'no visible chicken' / 'no meat', apply a heavy penalty (reduce score to <= 0.05).
    - If a candidate is Vada Pav / Dabeli, and features 'pav', 'bun', 'fried patty',
      'chutney', or 'sandwich' are present, reinforce candidate score.
    - Check margin between top and second candidates to evaluate ambiguity.
    """
    penalized: list[FoodCandidate] = []
    contradiction_log: list[str] = []

    # Detect global signals across all candidate reasons
    all_supporting = " ".join(" ".join(c.supporting_evidence) for c in candidates).lower()
    has_bread_structure = any(w in all_supporting for w in ["pav", "bun", "bread", "sandwich", "burger", "patty"])
    has_fried_vada = any(w in all_supporting for w in ["vada", "potato patty", "fritter", "besan", "fried patty"])

    for c in candidates:
        name_lower = c.name.lower()
        score = float(c.visual_score)
        supp_text = " ".join(c.supporting_evidence).lower()
        contra_text = " ".join(c.contradicting_evidence).lower()

        # Rule A: Chicken Curry / Meat Curry Contradiction Check
        is_meat_curry = any(k in name_lower for k in ["chicken", "curry", "murgh", "meat", "tariwala", "butter chicken"])
        if is_meat_curry:
            # If bread/pav/sandwich is detected or no chicken is visible, severely penalize
            if has_bread_structure or "no visible chicken" in contra_text or "no chicken" in contra_text or "sandwich" in supp_text or "pav" in supp_text:
                score = min(score, 0.05)
                c.contradicting_evidence.append("Severe contradiction: Bread/pav structure present; no visible chicken meat or curry bowl presentation.")
                contradiction_log.append(f"Penalized {c.name}: score reduced to {score:.2f} due to sandwich/pav structure.")

        # Rule B: Vada Pav / Dabeli Positive Reinforcement
        is_vada_pav = any(k in name_lower for k in ["vada pav", "wada pav", "batata vada pav", "bombay burger"])
        if is_vada_pav:
            if has_bread_structure and has_fried_vada:
                score = min(0.96, max(score, 0.82))
                c.supporting_evidence.append("Strong match: Pav bun with fried potato vada fritter and chutney confirmed.")

        c.visual_score = round(score, 2)
        penalized.append(c)

    # Sort descending by visual score
    penalized.sort(key=lambda x: x.visual_score, reverse=True)

    # Calculate Margin & State
    top_candidate = penalized[0] if penalized else None
    second_candidate = penalized[1] if len(penalized) > 1 else None

    top_score = top_candidate.visual_score if top_candidate else 0.0
    second_score = second_candidate.visual_score if second_candidate else 0.0
    margin = round(top_score - second_score, 2) if second_candidate else 1.0

    # Determine 3 Confidence States: "high", "medium", "needs_confirmation"
    has_top_contradiction = bool(top_candidate and len(top_candidate.contradicting_evidence) > 0 and any("severe" in e.lower() for e in top_candidate.contradicting_evidence))

    if top_score >= 0.72 and margin >= 0.20 and not has_top_contradiction and image_quality >= 0.5:
        confidence_state = "high"
        requires_confirmation = False
    elif top_score >= 0.55 and margin >= 0.10 and not has_top_contradiction:
        confidence_state = "medium"
        requires_confirmation = False
    else:
        confidence_state = "needs_confirmation"
        requires_confirmation = True

    eval_metadata = {
        "top_score": top_score,
        "second_score": second_score,
        "margin": margin,
        "confidence_state": confidence_state,
        "requires_confirmation": requires_confirmation,
        "contradiction_log": contradiction_log,
    }

    return penalized, eval_metadata


# ---------------------------------------------------------------------------
# 5. Public API: Multi-Candidate Recognition
# ---------------------------------------------------------------------------

def recognize_food_candidates(
    img: np.ndarray,
    user_hint: Optional[str] = None,
) -> Tuple[Optional[FoodRecognition], dict[str, Any]]:
    """
    Analyze image with Gemini using Pydantic structured multi-candidate output.
    Applies automatic fallback across models and evaluates contradiction penalties.

    Returns:
        (FoodRecognition, debug_dict)
    """
    client = _create_genai_client()
    if client is None:
        logger.debug("Gemini unavailable (missing GEMINI_API_KEY or import error).")
        return None, {"error": "Gemini API key not configured or import failed."}

    image_part = _prepare_image_part(img)
    if image_part is None:
        return None, {"error": "Could not convert image to Part."}

    user_text = _USER_PROMPT
    if user_hint and user_hint.strip():
        user_text += f"\nUser optional context: '{user_hint.strip()}' (verify against actual visible evidence)."

    import time
    last_error = None
    recognition: Optional[FoodRecognition] = None
    model_used = ""

    from google.genai import types

    # Try models in fallback order
    for model_name in GEMINI_MODELS:
        for attempt in range(2):
            try:
                logger.info("Attempting Gemini food recognition with model: %s (attempt %d)", model_name, attempt + 1)
                config = types.GenerateContentConfig(
                    system_instruction=_SYSTEM_PROMPT,
                    response_mime_type="application/json",
                    response_schema=FoodRecognition,
                    temperature=0.1,
                )

                response = client.models.generate_content(
                    model=model_name,
                    contents=[image_part, user_text],
                    config=config,
                )

                # Retrieve parsed Pydantic object
                if hasattr(response, "parsed") and isinstance(response.parsed, FoodRecognition):
                    recognition = response.parsed
                elif getattr(response, "text", None):
                    try:
                        recognition = FoodRecognition.model_validate_json(response.text)
                    except Exception:
                        data = json.loads(response.text)
                        recognition = FoodRecognition(**data)

                if recognition and recognition.candidates:
                    model_used = model_name
                    logger.info("Gemini %s returned %d candidates.", model_name, len(recognition.candidates))
                    break

            except Exception as exc:
                last_error = str(exc)
                logger.warning("Gemini model %s (attempt %d) failed: %s", model_name, attempt + 1, exc)
                if "503" in last_error or "UNAVAILABLE" in last_error:
                    time.sleep(1.0)
                    continue
                else:
                    break

        if recognition and recognition.candidates:
            break

    if recognition is None or not recognition.candidates:
        logger.warning("All Gemini candidate models failed. Last error: %s", last_error)
        return None, {"error": last_error or "No candidates returned."}

    # Apply contradiction penalties & candidate re-ranking
    evaluated_candidates, eval_meta = apply_contradiction_penalties(
        recognition.candidates,
        recognition.image_quality,
    )
    recognition.candidates = evaluated_candidates
    recognition.requires_confirmation = eval_meta["requires_confirmation"]

    debug_trace = {
        "model_used": model_used,
        "image_quality": recognition.image_quality,
        "confidence_state": eval_meta["confidence_state"],
        "margin": eval_meta["margin"],
        "top_score": eval_meta["top_score"],
        "second_score": eval_meta["second_score"],
        "contradiction_log": eval_meta["contradiction_log"],
        "candidates": [
            {
                "name": c.name,
                "score": c.visual_score,
                "reason": c.visual_reason,
                "supporting": c.supporting_evidence,
                "contradicting": c.contradicting_evidence,
            }
            for c in recognition.candidates
        ],
    }

    return recognition, debug_trace
